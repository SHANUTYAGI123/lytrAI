from typing import Optional, Literal, List
from pydantic import BaseModel, Field, field_validator


class ChatRequest(BaseModel):
    session_id: str = Field(
        ...,
        min_length=1,
        max_length=128,
        description="Required, 1-128 chars, generated by the client"
    )
    message: str = Field(
        ...,
        description="Required, 1-4000 chars after trimming whitespace"
    )
    system_prompt: Optional[str] = Field(
        None,
        description="Optional; overrides the default system prompt for this session"
    )

    @field_validator("session_id")
    @classmethod
    def validate_session_id(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("session_id cannot be empty")
        if len(v) > 128:
            raise ValueError("session_id must not exceed 128 characters")
        return v

    @field_validator("message")
    @classmethod
    def validate_message(cls, v: str) -> str:
        trimmed = v.strip()
        if len(trimmed) < 1:
            raise ValueError("message cannot be empty after trimming whitespace")
        if len(trimmed) > 4000:
            raise ValueError("message cannot exceed 4000 characters")
        return trimmed


class MetadataResponse(BaseModel):
    resolution_source: Literal["LIVE_INFERENCE", "LLM_CACHE"]
    model: str
    latency_ms: int
    input_tokens: int
    output_tokens: int
    key_id: Optional[str] = None
    fallback_attempts: int


class ChatResponse(BaseModel):
    session_id: str
    reply: str
    metadata: MetadataResponse


class HealthResponse(BaseModel):
    status: str
    keys_configured: int
    cache_enabled: bool


class MessageMetadata(BaseModel):
    resolution_source: Literal["LIVE_INFERENCE", "LLM_CACHE"]
    input_tokens: int
    output_tokens: int


class SessionMessageItem(BaseModel):
    role: Literal["user", "assistant"]
    content: str
    metadata: Optional[MessageMetadata] = None


class SessionHistoryResponse(BaseModel):
    session_id: str
    messages: List[SessionMessageItem]
